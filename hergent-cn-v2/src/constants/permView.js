/* ============================================================================
   permView.js —— 权限页「行」的**呈现层唯一源**（v349，2026-09-30）
   ============================================================================
   老板原话：**「请将权限项重新设计为：以侧栏暴露的功能模块、是否可使用 AI、
   以及可使用 Web 端或小程序端这四类维度组成。」**

   ---------------------------------------------------------------------------
   一、为什么要有本文件（病根）
   ---------------------------------------------------------------------------
   权限页的**行**来自后端 20 个模块（`core._ALL_MODULES` ← `server.list_modules()`），
   而老板脑子里是**侧栏那 10 个功能**（`Shell.vue` 的 `NAV`）。两个集合不是一一对应 ⇒
   产出三类"找不到框"：
     (a) 侧栏有、权限页**一行都没有**（`pages.js` 里 `module: null`）；
     (b) 有行但**名字对不上**（侧栏叫「目标与返利」，那一行叫「销售管理」）；
     (c) 7 个模块勾了在新前端**零变化**（纯接口数据闸门）。
   修法不是"再写一段解释文字"（v331 刚清掉那类文案），而是**让行 = 侧栏功能**。

   ---------------------------------------------------------------------------
   二、🔴 致命约束：本文件**只管显示**，勾选举仍写回**后端模块名**
   ---------------------------------------------------------------------------
   `pages.js::roleGateOpen` 第 ③ 档：**本行没有 `module` ⇒ 不让位 ⇒ 客户配不了**
   （这是安全阀 —— 否则"让位"会变成"全开"）。
   ⇒ 想让「按侧栏出行」**物理成立**，只能走两条路之一：
      · 路线 A（本文件）：把侧栏功能**映射**到既有模块，勾选仍写回原模块名 ⇒ 零后端风险；
      · 路线 B：给 `module: null` 的页建**真模块**（`_ALL_MODULES` + `_PATH_MODULE_MAP` +
        迁移脚本，三处缺一不可）⇒ 才能真正独立开关（v349 的 `loss` 就是这么拆出来的）。
   ⇒ **`module: null` 的行在本文件里必须是 `fixed`（只读说明），绝不能渲染可勾的框** ——
      勾了也不会生效，那就是"界面说假话"（本项目红线）。

   ---------------------------------------------------------------------------
   三、四类维度各自的判据（不要混为一谈）
   ---------------------------------------------------------------------------
     ① 侧栏功能模块 → 本文件 `PERM_SIDEBAR_GROUPS`（会话内裁决：`_check_perm` 按模块）
     ② 可用 AI       → `PERM_AI_MODULE`（= `chat`；会话内裁决，前端 `store.canUseAi()`）
     ③④ Web / 小程序端 → **不在这里** —— 它们在**登录那一刻**裁决
        （`users.login_scope` ← 角色政策 `role_end`），改它**只影响将来新建账号的默认值**，
        不动已有账号。把它们画进同一张表可以，**绝不能合并成一个勾**。

   护栏：`.workbuddy/tools/role-registry-consistency-check.py` 会锁
         本文件的 `module` 值 ⊆ `core._ALL_MODULES`，且侧栏项与 `Shell.vue NAV` 逐项一致。
   ============================================================================ */

