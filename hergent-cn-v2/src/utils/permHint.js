/**
 * 「去新建」类空态话术的唯一源。
 *
 * 🔴 为什么需要这个文件（v767）：
 *   页头的新建按钮普遍带门禁 —— `v-if="canDo('data','create')"`。
 *   只读角色能进这个页面（页面级门禁用的是「页面模块」），但**看不到那颗按钮**。
 *   而空态文案写的是无条件的「点右上角「+ 新增客户」」⇒ 用户照着去右上角找，
 *   那里什么都没有 ⇒ 结论是「系统坏了」，而不是「我没有权限」。
 *
 *   判据只有一条、实现只有一处（`store.canDo`），这里**只做话术翻译，不做权限判断**
 *   —— 各页仍然自己 `v-if="canDo(...)"`，绝不在这里另算一套。
 *
 * 🔴 话术里**不写菜单路径**。第一版写的是「让他在『角色管理』里放开写权限」，
 *   而这个系统里根本没有叫「角色管理」的菜单 —— 真名是「档案管理 › 组织相关 › 角色权限」
 *   （见 `constants/tabTitles.js` 的 `perm: '角色权限'`，侧栏名/标签栏/页面标题必须逐字一致）。
 *   也就是说，那句提示本身会变成刚修完的那类「指路指向不存在的东西」。
 *   结论：「找谁」比「点哪」稳 —— 菜单会改名、会挪位置，人不会。
 */

/** 把按钮上的「+」「＋」前缀去掉，只留动作名 —— 否则会读出「开通+ 新增客户权限」。 */
function actionOf(btnLabel) {
  return String(btnLabel || '').replace(/^[+＋]\s*/, '').trim()
}

/**
 * 无新建权限时的替代话术。
 * @param {string} btnLabel 空态原本指向的按钮名，如「+ 新增客户」
 * @returns {string}
 */
export function noNewPermHint(btnLabel) {
  const name = actionOf(btnLabel)
  return `当前账号是只读权限，不能${name} —— 需要的话请让管理员给这个角色放开写权限，`
    + `或换成有权限的账号登录。`
}

